@app.get("/")
def home():
    return render_template("index.html")

@app.get("/api/questions")
def get_questions():
    session["run_id"] = secrets.token_hex(12)
    session["started_at"] = time.time()
    return jsonify({"questions":[{"id":q["id"],"category":q["category"],"q":q["q"],"opts":q["opts"]} for q in QUESTIONS]})

@app.post("/api/check")
def check_answer():
    data = request.get_json(silent=True) or {}
    qid = data.get("id")
    choice = data.get("choice")
    if not isinstance(qid, int) or not isinstance(choice, int) or not -1 <= choice <= 3:
        return jsonify({"error":"داواکارییەکە دروست نییە."}), 400
    q = next((x for x in QUESTIONS if x["id"] == qid), None)
    if not q:
        return jsonify({"error":"پرسیار نەدۆزرایەوە."}), 404
    return jsonify({"correct":choice == q["a"],"correctIndex":q["a"],"explanation":q["why"]})

